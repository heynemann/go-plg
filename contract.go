package plg

import (
	"errors"
	"fmt"
	"io/fs"
	"reflect"

	"github.com/puzpuzpuz/xsync/v4"

	"github.com/heynemann/go-plg/internal/goabi"
	"github.com/heynemann/go-plg/internal/memfs"
)

// Contract is what plg needs to serve an interface, beyond its reflect type: Go cannot create a type with
// methods at run time, so each interface needs a compiled adapter, and Go plugins import the contract
// package, so the guest needs its source. `plg gen` generates both and registers them from init:
//
//	//go:generate go run github.com/heynemann/go-plg/cmd/plg gen Fooer
type Contract struct {
	// Interface is the interface type, such as reflect.TypeFor[Fooer]().
	Interface reflect.Type
	// Adapter is a struct type with one field W<Method> per interface method, of exactly the method's
	// type, and whose pointer implements Interface by forwarding each method to its field.
	Adapter reflect.Type
	// Source holds the Go source files of the interface's package at its root. The Go guest interprets them,
	// so they may import only packages the guest allows.
	Source fs.FS
}

// contract is a registered Contract, prepared once: the method plans, the source snapshot, and the dispatcher
// and init payload of its Go plugins.
type contract struct {
	iface      reflect.Type
	adapter    reflect.Type
	source     *memfs.FS
	dispatcher []byte
	payload    []byte
	methods    []*method
}

// contracts holds every registered contract, keyed by interface type.
//
//nolint:gochecknoglobals // init-time registry filled by the generated code of contract packages
var contracts = xsync.NewMap[reflect.Type, *contract]()

var (
	errNoInterface  = errors.New("nil Interface")
	errAdapterType  = errors.New("adapter is not a struct type")
	errAdapterField = errors.New("adapter lacks the field")
	errAdapterImpl  = errors.New("adapter pointer does not implement the interface")
	errNoSource     = errors.New("nil Source")
	errNoGoFiles    = errors.New("source has no .go file at its root")
	errRegistered   = errors.New("interface already has a contract")
)

// RegisterContract registers a contract, making its interface available to Register. It fails if the
// interface breaks the interface contract, if the adapter does not match the interface, if the source cannot
// be read, or if the interface already has a contract. It is safe for concurrent use.
func RegisterContract(spec Contract) error {
	if spec.Interface == nil {
		return fmt.Errorf("%w: %w", ErrInvalidContract, errNoInterface)
	}

	err := validateInterface(spec.Interface)
	if err != nil {
		return fmt.Errorf("%w: %w", ErrInvalidContract, err)
	}

	prepared, err := prepareContract(&spec)
	if err != nil {
		return fmt.Errorf("%w for %s: %w", ErrInvalidContract, spec.Interface, err)
	}

	if _, dup := contracts.LoadOrStore(spec.Interface, prepared); dup {
		return fmt.Errorf("%w: %s: %w", ErrInvalidContract, spec.Interface, errRegistered)
	}

	return nil
}

// MustRegisterContract is like [RegisterContract] but panics if the contract is invalid. Code generated by
// `plg gen` calls it from init: an invalid contract is a programming error, caught when the program starts.
func MustRegisterContract(spec Contract) {
	err := RegisterContract(spec)
	if err != nil {
		panic(err)
	}
}

func prepareContract(spec *Contract) (*contract, error) {
	fields, err := adapterFields(spec.Interface, spec.Adapter)
	if err != nil {
		return nil, err
	}

	prepared := &contract{iface: spec.Interface, adapter: spec.Adapter}

	prepared.source, err = snapshotSource(spec.Source)
	if err != nil {
		return nil, err
	}

	// The interface passed validation, so the dispatcher renders and the payload encodes.
	prepared.dispatcher, err = goabi.RenderDispatcher(spec.Interface)
	if err != nil {
		return nil, fmt.Errorf("rendering the Go dispatcher: %w", err)
	}

	payload := goabi.InitPayload{GoPath: goabi.GoPath, Dispatch: goabi.DispatchImportPath}

	for i, field := range fields {
		var meth *method

		meth, err = newMethod(spec.Interface, i, field)
		if err != nil {
			return nil, err
		}

		prepared.methods = append(prepared.methods, meth)
		payload.Methods = append(payload.Methods, meth.name)
	}

	prepared.payload, err = payload.Append(nil)
	if err != nil {
		return nil, fmt.Errorf("encoding the Go init payload: %w", err)
	}

	return prepared, nil
}

// adapterFields returns, per interface method, the index of the adapter's W<Method> field.
func adapterFields(iface, adapter reflect.Type) ([]int, error) {
	if adapter == nil || adapter.Kind() != reflect.Struct {
		return nil, fmt.Errorf("%w: %v", errAdapterType, adapter)
	}

	fields := make([]int, iface.NumMethod())
	for i := range fields {
		m := iface.Method(i)

		field, ok := adapter.FieldByName("W" + m.Name)
		if !ok || len(field.Index) != 1 || field.Type != m.Type {
			return nil, fmt.Errorf("%w W%s %s", errAdapterField, m.Name, m.Type)
		}

		fields[i] = field.Index[0]
	}

	if !reflect.PointerTo(adapter).Implements(iface) {
		return nil, fmt.Errorf("%w: *%s", errAdapterImpl, adapter)
	}

	return fields, nil
}

// snapshotSource copies the contract source, so every plugin of the contract sees the same files.
func snapshotSource(src fs.FS) (*memfs.FS, error) {
	if src == nil {
		return nil, errNoSource
	}

	var tree memfs.Builder

	err := tree.AddTree(".", src, ".")
	if err != nil {
		return nil, fmt.Errorf("reading the source: %w", err)
	}

	snapshot, err := tree.Build()
	if err != nil {
		return nil, fmt.Errorf("reading the source: %w", err)
	}

	goFiles, err := fs.Glob(snapshot, "*.go")
	if err != nil || len(goFiles) == 0 {
		return nil, errNoGoFiles
	}

	return snapshot, nil
}

// lookupContract returns the contract registered for iface.
func lookupContract(iface reflect.Type) (*contract, error) {
	ct, ok := contracts.Load(iface)
	if !ok {
		return nil, fmt.Errorf("%w for %s: run `go generate` (with //go:generate go run "+
			"github.com/heynemann/go-plg/cmd/plg gen %s) in package %s, or call plg.RegisterContract",
			ErrNoContract, iface, iface.Name(), iface.PkgPath())
	}

	return ct, nil
}
