// method is the call plan of one interface method, built once per contract: the codecs of its arguments
// (after the context) and of its results (before the error). Calls never plan a type again.
type method struct {
	typ     reflect.Type
	name    string
	args    []*wire.Codec
	results []*wire.Codec
	zeros   []reflect.Value // the results returned with an error: zero values, then a nil error
	field   int             // index of the adapter's W<name> field
	index   uint32          // the method index of plg_call
}

// newMethod plans sig, the method with the given index; planner is shared by the contract's methods, so each type
// of the contract is planned once.
func newMethod(planner *wire.Planner, sig *reflect.Method, index, field int) (*method, error) {
	fn := sig.Type
	plan := &method{
		typ:     fn,
		name:    sig.Name,
		field:   field,
		index:   uint32(index), //nolint:gosec // G115: a method index is far below 2^32
		args:    make([]*wire.Codec, 0, fn.NumIn()-1),
		results: make([]*wire.Codec, 0, fn.NumOut()-1),
	}

	for k := 1; k < fn.NumIn(); k++ {
		codec, err := planner.For(fn.In(k))
		if err != nil {
			return nil, fmt.Errorf("method %s: parameter %d: %w", sig.Name, k, err)
		}

		plan.args = append(plan.args, codec)
	}

	for k := range fn.NumOut() - 1 {
		codec, err := planner.For(fn.Out(k))
		if err != nil {
			return nil, fmt.Errorf("method %s: result %d: %w", sig.Name, k, err)
		}

		plan.results = append(plan.results, codec)
	}

	for typ := range fn.Outs() {
		plan.zeros = append(plan.zeros, reflect.Zero(typ))
	}

	return plan, nil
}

// encodeArgs appends the encoding of the arguments after the context.
func (m *method) encodeArgs(dst []byte, args []reflect.Value) ([]byte, error) {
	for k, codec := range m.args {
		next, err := codec.Append(dst, args[k+1])
		if err != nil {
			return dst, fmt.Errorf("parameter %d: %w", k+1, err)
		}

		dst = next
	}

	return dst, nil
}

// decodeResults decodes the method's results from reader into out (one value per result), ending with a nil
// error.
func (m *method) decodeResults(reader *wire.Reader, out []reflect.Value) error {
	for k, codec := range m.results {
		out[k] = reflect.New(codec.Type()).Elem()

		err := codec.Decode(reader, out[k])
		if err != nil {
			return fmt.Errorf("result %d: %w", k, err)
		}
	}

	out[len(out)-1] = m.zeros[len(out)-1]

	return nil
}

// decodeArgs decodes the arguments after the context from body, returning the call's arguments with ctx first.
func (m *method) decodeArgs(ctx context.Context, body []byte) ([]reflect.Value, error) {
	args := make([]reflect.Value, len(m.args)+1)
	args[0] = reflect.ValueOf(ctx)
	reader := wire.NewReader(body)

	for k, codec := range m.args {
		args[k+1] = reflect.New(codec.Type()).Elem()

		err := codec.Decode(&reader, args[k+1])
		if err != nil {
			return nil, fmt.Errorf("parameter %d: %w", k+1, err)
		}
	}

	err := reader.End()
	if err != nil {
		return nil, fmt.Errorf("arguments: %w", err)
	}

	return args, nil
}

// encodeResults appends the encoding of the results before the final error.
func (m *method) encodeResults(dst []byte, out []reflect.Value) ([]byte, error) {
	for k, codec := range m.results {
		next, err := codec.Append(dst, out[k])
		if err != nil {
			return dst, fmt.Errorf("result %d: %w", k, err)
		}

		dst = next
	}

	return dst, nil
}

// failed returns the method's zero results with err.
func (m *method) failed(err error) []reflect.Value {
	out := make([]reflect.Value, len(m.zeros))
	copy(out, m.zeros)

	out[len(out)-1] = reflect.ValueOf(&err).Elem()

	return out
}

var errNilContext = errors.New("nil context")

// reflectCall is one call through the generic binder: its arguments and results as reflect values.
type reflectCall struct {
	// small backs out for methods with up to two results, the error included, sparing an allocation per call.
	small [2]reflect.Value
	meth  *method
	args  []reflect.Value // ctx first
	out   []reflect.Value // set by a successful DecodeResults
}

// AppendArgs implements [plgimpl.Call].
func (rc *reflectCall) AppendArgs(b []byte) ([]byte, error) {
	return rc.meth.encodeArgs(b, rc.args)
}

// DecodeResults implements [plgimpl.Call].
func (rc *reflectCall) DecodeResults(reader *wire.Reader) error {
	out := rc.small[:]
	if n := len(rc.meth.zeros); n <= len(out) {
		out = out[:n]
	} else {
		out = make([]reflect.Value, n)
	}

	err := rc.meth.decodeResults(reader, out)
	if err != nil {
		return err
	}

	rc.out = out

	return nil
}

// invoker is the [plgimpl.Invoker] of an adapter generated by `plg gen`: it calls the plugin c serves under key.
type invoker struct {
	c   *Container
	ct  *contract
	key string
}

// Invoke implements [plgimpl.Invoker].
func (inv *invoker) Invoke(ctx context.Context, method int, call plgimpl.Call) error {
	return inv.c.call(ctx, inv.key, inv.ct.methods[method], call)
}

// bind returns a new adapter for the plugin c serves under key, implementing the contract's interface: the one
// `plg gen` generated (see [Contract.Fast]), or else a pointer to the contract's adapter struct whose W<Method>
// fields call that plugin through reflection. Each call runs on the generation of the plugin c serves when the
// call starts, so an adapter keeps working across reloads.
func (ct *contract) bind(ctr *Container, key string) any {
	if ct.fast != nil && !ctr.genericBinder.Load() {
		return ct.fast(&invoker{c: ctr, ct: ct, key: key})
	}

	adapter := reflect.New(ct.adapter)
	fields := adapter.Elem()

	for _, meth := range ct.methods {
		fields.Field(meth.field).Set(reflect.MakeFunc(meth.typ, func(args []reflect.Value) []reflect.Value {
			ctx, _ := reflect.TypeAssert[context.Context](args[0]) // nil for a nil context
			call := reflectCall{meth: meth, args: args}

			err := ctr.call(ctx, key, meth, &call)
			if err != nil {
				return meth.failed(err)
			}

			return call.out
		}))
	}

	return adapter.Interface()
}

// call runs one method call on the generation of the plugin c serves under key, counted in flight on it until
// it ends.
func (c *Container) call(ctx context.Context, key string, meth *method, call plgimpl.Call) error {
	if ctx == nil {
		return fmt.Errorf("plg: %s.%s: %w", key, meth.name, errNilContext)
	}

	gen, err := c.serving(key)
	if err != nil {
		return fmt.Errorf("plg: %s.%s: %w", key, meth.name, err)
	}

	defer gen.leave()

	return gen.call(ctx, meth, call)
}

// call runs one method call on an instance of the plugin, waiting for one while all are busy, and records it in
// the plugin's call metrics and its span.
func (p *plugin) call(ctx context.Context, meth *method, call plgimpl.Call) error {
	start := time.Now()
	ctx, span := p.spans.call(ctx, meth.index)
	err := p.callInstance(ctx, meth, call)
	p.pool.called(ctx, meth.index, time.Since(start), err)
	p.spans.called(ctx, span, err)

	return err
}

// callInstance is call without its metrics.
func (p *plugin) callInstance(ctx context.Context, meth *method, call plgimpl.Call) error {
	held, err := p.pool.acquire(ctx)
	if err != nil {
		return fmt.Errorf("plg: %s.%s: %w", p.key, meth.name, err)
	}

	discard, err := p.exchange(ctx, held, meth, call)
	if discard || held.inst.Broken() { // never reuse a broken instance: wazero would answer with garbage
		p.pool.discard(ctx, held)
	} else {
		p.pool.release(ctx, held)
	}

	return err
}

// exchange encodes the arguments, calls the instance and decodes its answer into call. The boolean reports an
// instance that must not serve another call. A guest that traps, panics, is stopped by ctx or breaks the ABI,
// and a panic on the host meanwhile (in the codec, generated code included), fail the call with a reported
// [PanicError] in [PhaseCall].
func (p *plugin) exchange(ctx context.Context, held *slot, meth *method, call plgimpl.Call) (bool, error) {
	var (
		discard bool
		err     error
	)

	func() {
		defer func() {
			if v := recover(); v != nil {
				failure := &PanicError{
					Key: p.key, Language: p.desc.Language, Phase: PhaseCall, Method: meth.name, Owner: *p.desc.owner(),
					tags: p.pool.owner,
				}
				p.pool.panics.recovered(ctx, failure, v)

				discard, err = true, failure
			}
		}()

		discard, err = p.roundTrip(ctx, held, meth, call)
	}()

	return discard, err
}

// roundTrip is exchange without its panic boundary.
func (p *plugin) roundTrip(ctx context.Context, held *slot, meth *method, call plgimpl.Call) (bool, error) {
	var err error

	held.buf, err = call.AppendArgs(held.buf[:0])
	if err != nil {
		return false, fmt.Errorf("%w: %s.%s: %w", ErrConversion, p.key, meth.name, err)
	}

	res, err := held.inst.Call(ctx, meth.index, held.buf)
	if err != nil {
		return p.callFailed(ctx, held, meth, err)
	}

	switch res.Status { //nolint:exhaustive // load and ABI statuses (or worse) fail the call and break the instance
	case wire.StatusOK:
		err = decodeResults(res.Body, call)
		if err != nil {
			return true, p.failed(ctx, held, meth, fmt.Errorf("%w: %w", engine.ErrABI, err))
		}

		return false, nil
	case wire.StatusError:
		return false, &PluginError{Key: p.key, Method: meth.name, Message: res.Message, Owner: *p.desc.owner()}
	case wire.StatusConvert:
		return false, fmt.Errorf("%w: %s.%s: %s", ErrConversion, p.key, meth.name, res.Message)
	case wire.StatusPanic:
		return true, p.failed(ctx, held, meth, res.Message)
	default:
		return true, p.failed(ctx, held, meth, fmt.Errorf("%w %s: %s", errGuestStatus, res.Status, res.Message))
	}
}

// callFailed handles a call its instance failed with err: the container closed under it ([ErrClosed]), a
// multiplexed instance failed it without a guest failure of its own, or the guest failed, which is reported. The
// boolean reports an instance that must not serve another call.
func (p *plugin) callFailed(ctx context.Context, held *slot, meth *method, err error) (bool, error) {
	if errors.Is(err, engine.ErrStopped) { // no guest failure to report
		return true, fmt.Errorf("plg: %s.%s: %w", p.key, meth.name, ErrClosed)
	}

	if lost, ok := errors.AsType[*muxError](err); ok { // no guest failure of its own: nothing to report
		return lost.discard, fmt.Errorf("plg: %s.%s: %w", p.key, meth.name, lost)
	}

	return true, p.failed(ctx, held, meth, err)
}

// decodeResults decodes a successful call's results from body into call, which must consume all of it.
func decodeResults(body []byte, call plgimpl.Call) error {
	reader := wire.NewReader(body)

	err := call.DecodeResults(&reader)
	if err != nil {
		return err //nolint:wrapcheck // the call names the result and the place in it; roundTrip adds the rest
	}

	err = reader.End()
	if err != nil {
		return fmt.Errorf("results: %w", err)
	}

	return nil
}

// failed reports a call the guest failed, with what the guest wrote to stderr meanwhile.
func (p *plugin) failed(ctx context.Context, held *slot, meth *method, value any) *PanicError {
	failure := &PanicError{
		Key: p.key, Language: p.desc.Language, Phase: PhaseCall, Method: meth.name, Value: value,
		Guest: held.inst.Guest(), Owner: *p.desc.owner(), tags: p.pool.owner,
	}
	p.pool.panics.report(ctx, failure)

	return failure
}
