// quickStart is the quick start as the README tells it: commands to type, files to write, the expected output.
type quickStart struct {
	files    map[string]string
	output   string
	commands []string
}

var (
	marker    = regexp.MustCompile(`^<!-- quickstart:(commands|output|file (\S+)) -->$`)
	errFormat = errors.New("malformed quick start")
)

// parseQuickStart reads the code blocks of the README that a quickstart marker comment precedes.
func parseQuickStart(readme string) (quickStart, error) {
	quick := quickStart{files: map[string]string{}}
	lines := strings.Split(readme, "\n")

	for i := 0; i < len(lines); i++ {
		match := marker.FindStringSubmatch(lines[i])
		if match == nil {
			continue
		}

		if i+1 == len(lines) || !strings.HasPrefix(lines[i+1], "```") {
			return quick, fmt.Errorf("%w: README.md:%d: no code block after the marker", errFormat, i+1)
		}

		start := i + 2

		end := slices.Index(lines[start:], "```")
		if end < 0 {
			return quick, fmt.Errorf("%w: README.md:%d: unterminated code block", errFormat, i+2)
		}

		block := lines[start : start+end]
		i = start + end

		switch match[1] {
		case "commands":
			quick.commands = append(quick.commands, block...)
		case "output":
			quick.output = strings.Join(block, "\n") + "\n"
		default:
			quick.files[match[2]] = strings.Join(block, "\n") + "\n"
		}
	}

	return quick, nil
}

// The README's quick start, run in a fresh module exactly as written, except for what needs the network: the
// module requires plg from this checkout instead of fetching it, and resolves plg's own requirements from the
// module cache.
func TestReadmeQuickStart(t *testing.T) {
	t.Parallel()

	root, err := filepath.Abs(filepath.Join("..", ".."))
	require.NoError(t, err)

	readme, err := os.ReadFile(filepath.Join(root, "README.md")) //nolint:gosec // G304: this checkout's README
	require.NoError(t, err)

	quick, err := parseQuickStart(string(readme))
	require.NoError(t, err)

	require.Equal(t, []string{
		"mkdir quickstart && cd quickstart",
		"go mod init example.com/quickstart",
		"go get github.com/heynemann/go-plg@latest",
		"go mod tidy",
		"go generate ./...",
		"go run .",
	}, quick.commands, "the commands this test knows how to run")
	require.Len(t, quick.files, 8, "the contract, three plugins of two files and the program")
	require.NotEmpty(t, quick.output)

	dir := t.TempDir() // stands for `mkdir quickstart && cd quickstart`

	for name, content := range quick.files {
		require.NoError(t, os.MkdirAll(filepath.Join(dir, filepath.Dir(name)), 0o750))
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600))
	}

	var output string

	for _, command := range quick.commands[1:] {
		args := strings.Fields(command)
		if command == "go get github.com/heynemann/go-plg@latest" {
			args = []string{
				"go", "mod", "edit", "-require=github.com/heynemann/go-plg@v0.0.0",
				"-replace=github.com/heynemann/go-plg=" + root,
			}
		}

		var stderr strings.Builder

		//nolint:gosec // G204: runs the README's go commands in the test's own module
		cmd := exec.CommandContext(t.Context(), args[0], args[1:]...)
		cmd.Dir = dir
		cmd.Stderr = &stderr

		cmd.Env = append(os.Environ(), "GOWORK=off", "GOPROXY=off", "GOFLAGS=")

		out, runErr := cmd.Output()
		require.NoError(t, runErr, "%s: %s", command, stderr.String())

		output = string(out)
	}

	assert.Equal(t, quick.output, output, "the program prints what the README shows")

	//nolint:gosec // G304: the file go generate wrote in the test's module
	generated, err := os.ReadFile(filepath.Join(dir, "greeter", "greeter_plg.go"))
	require.NoError(t, err)
	assert.Contains(t, string(generated), "// Code generated by plg gen. DO NOT EDIT.",
		"go generate wrote the file the README names")
}

func TestParseQuickStartRejectsMalformedMarkers(t *testing.T) {
	t.Parallel()

	tests := map[string]string{
		"no block":       "<!-- quickstart:output -->\ntext\n",
		"end of file":    "<!-- quickstart:output -->\n",
		"unterminated":   "<!-- quickstart:file a.go -->\n```go\npackage a\n",
		"block too late": "<!-- quickstart:commands -->\n\n```sh\ngo run .\n```\n",
	}

	for name, readme := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			_, err := parseQuickStart(readme)
			require.ErrorIs(t, err, errFormat)
		})
	}

	quick, err := parseQuickStart("<!-- quickstart:file a/b.go -->\n```go\npackage b\n\n```\n<!-- other -->\n")
	require.NoError(t, err)
	assert.Equal(t, map[string]string{"a/b.go": "package b\n\n"}, quick.files)
}
