// Package buildguest implements `plg build-guest`: it builds a custom Go guest, the default guest plus the
// yaegi symbol tables of extra packages, so that Go plugins run by it may import those packages.
//
// The guest is built in a temporary module that takes the service module's requirements (its go.mod and
// go.sum, with local replacements made absolute), so plg and the extra packages resolve to the versions the
// service builds with. Its main package links the guest ABI (guestsrc/golang/reactor, which links
// internal/goguest and the default symbol tables) and a package whose init adds the extra symbol tables,
// extracted with yaegi extract for GOOS=wasip1 as `make symbols` does for the default ones. The module is
// built like `make guests` builds the default guest: a wasip1 reactor, -trimpath, without VCS stamping.
package buildguest

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"slices"
	"strings"

	"github.com/bytedance/sonic"

	"github.com/heynemann/go-plg/internal/goallow"
)

// Errors returned by [Build], wrapped with details.
var (
	// ErrPackages reports missing, repeated or already allowlisted extra packages.
	ErrPackages = errors.New("invalid extra packages")
	// ErrModule reports a directory outside a Go module, or a module that does not provide plg or an extra
	// package.
	ErrModule = errors.New("the service module cannot build the guest")
	// ErrGo reports a failing go command, with its output.
	ErrGo = errors.New("go command failed")
	// ErrExtract reports a package whose symbols yaegi cannot extract, with its output.
	ErrExtract = errors.New("extracting the package symbols failed")
)

const (
	// plgModule is the module the guest's main package imports the guest ABI from.
	plgModule = "github.com/heynemann/go-plg"
	// reactorImport links the guest ABI exports (and through them internal/goguest and the default symbols).
	reactorImport = plgModule + "/guestsrc/golang/reactor"
	// symbolsImport is the default guest's symbol table registry, which the extra tables join.
	symbolsImport = plgModule + "/guestsrc/golang/symbols"
	// guestModule is the temporary module's path; extraPackage is the name of its package of extra symbols.
	guestModule  = "plg.local/customguest"
	extraPackage = "extra"
	// yaegiCmd is yaegi's command, whose extract subcommand `make symbols` runs too.
	yaegiCmd = "github.com/traefik/yaegi/cmd/yaegi"
	// The permissions of the temporary module's directories and files.
	dirMode  = 0o750
	fileMode = 0o600
)

// mainSource is the guest's main package.
const mainSource = `// Code generated by plg build-guest. DO NOT EDIT.

//go:build wasip1

// Command customguest is a custom plg Go guest: the default guest plus the packages in ./` + extraPackage + `.
package main

import (
	_ "` + reactorImport + `"
	_ "` + guestModule + "/" + extraPackage + `"
)

func main() {}
`

// extraSource declares the symbol table the extracted files fill: the default guest's.
const extraSource = `// Code generated by plg build-guest. DO NOT EDIT.

// Package ` + extraPackage + ` adds the symbol tables of the custom guest's extra packages to the default guest's.
package ` + extraPackage + `

import "` + symbolsImport + `"

// Symbols is the guest's symbol table registry; the extracted files of this package add to it.
var Symbols = symbols.Symbols
`

// Options configure [Build].
type Options struct {
	// Dir is a directory inside the service's Go module.
	Dir string
	// Output is the path of the guest module to write; relative to Dir unless absolute.
	Output string
	// Packages are the import paths of the extra packages: standard library packages outside the default
	// allowlist, or pure-Go packages of modules the service module requires.
	Packages []string
}

// Build builds the custom guest described by opts and writes it to opts.Output.
func Build(ctx context.Context, opts Options) error {
	err := checkPackages(opts.Packages)
	if err != nil {
		return err
	}

	gomod, err := goOutput(ctx, opts.Dir, nil, "env", "GOMOD")
	if err != nil {
		return err
	}

	gomod = strings.TrimSpace(gomod)
	if gomod == "" || gomod == os.DevNull {
		return fmt.Errorf("%w: %s is not inside a Go module", ErrModule, opts.Dir)
	}

	output, err := filepath.Abs(resolve(opts.Dir, opts.Output))
	if err != nil {
		return fmt.Errorf("resolving the output path: %w", err)
	}

	dir, err := os.MkdirTemp("", "plg-build-guest-")
	if err != nil {
		return fmt.Errorf("creating the build directory: %w", err)
	}

	work, err := os.OpenRoot(dir)
	if err == nil {
		b := builder{work: work, service: filepath.Dir(gomod)}
		err = errors.Join(b.build(ctx, opts.Packages, output), work.Close())
	}

	return errors.Join(err, os.RemoveAll(dir))
}

// resolve returns name, relative to dir unless absolute.
func resolve(dir, name string) string {
	if filepath.IsAbs(name) {
		return name
	}

	return filepath.Join(dir, name)
}

// checkPackages rejects an empty list, repeated packages and packages the default guest already has.
func checkPackages(pkgs []string) error {
	if len(pkgs) == 0 {
		return fmt.Errorf("%w: name at least one package", ErrPackages)
	}

	for i, pkg := range pkgs {
		switch {
		case pkg == "" || strings.HasPrefix(pkg, ".") || filepath.IsAbs(pkg):
			return fmt.Errorf("%w: %q is not an import path", ErrPackages, pkg)
		case slices.Contains(pkgs[:i], pkg):
			return fmt.Errorf("%w: %s is listed twice", ErrPackages, pkg)
		case goallow.Allowed(pkg):
			return fmt.Errorf("%w: %s is in the default allowlist already", ErrPackages, pkg)
		}
	}

	return nil
}

// builder builds one guest in the temporary module work, from the service module rooted at service.
type builder struct {
	work    *os.Root
	service string
}

func (b *builder) build(ctx context.Context, pkgs []string, output string) error {
	err := b.module(ctx)
	if err == nil {
		err = b.checkProvided(ctx, pkgs)
	}

	if err == nil {
		err = b.extract(ctx, pkgs)
	}

	if err != nil {
		return err
	}

	_, err = goOutput(ctx, b.work.Name(), []string{"GOOS=wasip1", "GOARCH=wasm"},
		"build", "-trimpath", "-buildvcs=false", "-buildmode=c-shared", "-o", output, ".")

	return err
}

// modVersion is a module path and version in `go mod edit -json`'s output.
type modVersion struct {
	Path    string
	Version string
}

// replacement is a replace directive in `go mod edit -json`'s output.
type replacement struct {
	Old modVersion
	New modVersion
}

// goModFile is the part of `go mod edit -json`'s output the build needs.
type goModFile struct {
	Replace []replacement
}

// module sets up the temporary module: the service's go.mod under the guest module's path, its local
// replacements made absolute, and its go.sum.
func (b *builder) module(ctx context.Context) error {
	err := b.copyModuleFiles()
	if err != nil {
		return err
	}

	out, err := goOutput(ctx, b.work.Name(), nil, "mod", "edit", "-json")
	if err != nil {
		return err
	}

	var mod goModFile

	err = sonic.UnmarshalString(out, &mod)
	if err != nil {
		return fmt.Errorf("%w: reading go mod edit -json: %w", ErrGo, err)
	}

	edits := []string{"mod", "edit", "-module=" + guestModule}

	for _, repl := range mod.Replace {
		if isRelativeDir(repl.New.Path) {
			edits = append(edits, "-replace="+repl.old()+"="+filepath.Join(b.service, repl.New.Path))
		}
	}

	_, err = goOutput(ctx, b.work.Name(), nil, edits...)

	return err
}

// old is the replaced module as `go mod edit -replace` takes it: path, or path@version.
func (r *replacement) old() string {
	if r.Old.Version == "" {
		return r.Old.Path
	}

	return r.Old.Path + "@" + r.Old.Version
}

// copyModuleFiles copies the service's go.mod and go.sum, if it has one, into the temporary module.
func (b *builder) copyModuleFiles() error {
	service := os.DirFS(b.service)

	for _, name := range []string{"go.mod", "go.sum"} {
		data, err := fs.ReadFile(service, name)
		if errors.Is(err, fs.ErrNotExist) && name == "go.sum" {
			continue
		}

		if err == nil {
			err = b.work.WriteFile(name, data, fileMode)
		}

		if err != nil {
			return fmt.Errorf("copying the service's %s: %w", name, err)
		}
	}

	return nil
}

// isRelativeDir reports whether a replacement is a directory relative to the go.mod's, as the go command
// decides (other replacements are absolute directories or modules).
func isRelativeDir(dir string) bool {
	return dir == "." || dir == ".." ||
		strings.HasPrefix(dir, "./") || strings.HasPrefix(dir, "../") ||
		strings.HasPrefix(dir, `.\`) || strings.HasPrefix(dir, `..\`)
}

// checkProvided checks that the service's build list has plg and the module of every extra package outside the
// standard library, so that nothing resolves to a version the service does not build with.
func (b *builder) checkProvided(ctx context.Context, pkgs []string) error {
	out, err := goOutput(ctx, b.work.Name(), nil, "list", "-m", "-f", "{{.Path}}", "all")
	if err != nil {
		return err
	}

	modules := strings.Fields(out)

	if !slices.Contains(modules, plgModule) {
		return fmt.Errorf("%w: it does not require %s", ErrModule, plgModule)
	}

	for _, pkg := range pkgs {
		if isStandard(pkg) {
			continue
		}

		provided := slices.ContainsFunc(modules, func(mod string) bool {
			return pkg == mod || strings.HasPrefix(pkg, mod+"/")
		})
		if !provided {
			return fmt.Errorf("%w: no module it requires provides %s (go get it in the service module first)",
				ErrModule, pkg)
		}
	}

	return nil
}

// isStandard reports whether an import path is the standard library's: its first element has no dot.
func isStandard(pkg string) bool {
	first, _, _ := strings.Cut(pkg, "/")

	return !strings.Contains(first, ".")
}

// extract writes the guest's packages: main, and the extra package with its symbol table declaration and one
// file per package, extracted by yaegi for wasip1.
func (b *builder) extract(ctx context.Context, pkgs []string) error {
	err := b.work.Mkdir(extraPackage, dirMode)
	if err == nil {
		err = b.work.WriteFile(path.Join(extraPackage, extraPackage+".go"), []byte(extraSource), fileMode)
	}

	if err == nil {
		err = b.work.WriteFile("main.go", []byte(mainSource), fileMode)
	}

	if err != nil {
		return fmt.Errorf("writing the guest's sources: %w", err)
	}

	yaegi := filepath.Join(b.work.Name(), "yaegi")

	// For the machine running it, whatever GOOS and GOARCH the environment sets.
	_, err = goOutput(ctx, b.work.Name(), []string{"GOOS=", "GOARCH="}, "build", "-o", yaegi, yaegiCmd)
	if err != nil {
		return err
	}

	//nolint:gosec // G204: the yaegi command just built, with import paths checkPackages accepted
	cmd := exec.CommandContext(ctx, yaegi, append([]string{"extract", "-name", extraPackage}, pkgs...)...)
	cmd.Dir = filepath.Join(b.work.Name(), extraPackage)
	cmd.Env = goEnv([]string{"GOOS=wasip1", "GOARCH=wasm"})

	// yaegi extract reports a package it cannot extract and goes on with the others (exiting 0), so a missing
	// file is the failure too.
	out, err := cmd.CombinedOutput()
	if missing := b.firstUnextracted(pkgs); err != nil || missing != "" {
		return fmt.Errorf("%w: yaegi extract (%s) wrote no symbols for %q:\n%s", ErrExtract, cmd.ProcessState,
			missing, bytes.TrimSpace(out))
	}

	return nil
}

// firstUnextracted returns the first of pkgs yaegi extract wrote no file for, or "" when it wrote them all.
func (b *builder) firstUnextracted(pkgs []string) string {
	files := strings.NewReplacer("/", "-", ".", "_", "~", "_") // yaegi's file naming

	for _, pkg := range pkgs {
		_, err := b.work.Stat(path.Join(extraPackage, files.Replace(pkg)+".go"))
		if err != nil {
			return pkg
		}
	}

	return ""
}

// goOutput runs the go command in dir with extra environment variables and returns its standard output; a
// failure carries the command's output.
func goOutput(ctx context.Context, dir string, env []string, args ...string) (string, error) {
	cmd := exec.CommandContext(ctx, "go", args...) //nolint:gosec // G204: the go command with plg's own arguments
	cmd.Dir = dir
	cmd.Env = goEnv(env)

	var stdout, stderr bytes.Buffer

	cmd.Stdout, cmd.Stderr = &stdout, &stderr

	err := cmd.Run()
	if err != nil {
		return "", fmt.Errorf("%w: go %s: %w\n%s", ErrGo, strings.Join(args, " "), err,
			bytes.TrimSpace(stderr.Bytes()))
	}

	return stdout.String(), nil
}

// goEnv is the environment of the go commands: the process's, without workspaces (the temporary module is in
// none), letting the go command record missing go.sum hashes of modules the service builds without (yaegi,
// for one), plus extra.
func goEnv(extra []string) []string {
	return append(os.Environ(), append([]string{"GOWORK=off", "GOFLAGS=" + goflags()}, extra...)...)
}

// goflags is the environment's GOFLAGS with -mod=mod last, so that it wins.
func goflags() string {
	return strings.TrimSpace(os.Getenv("GOFLAGS") + " -mod=mod")
}
