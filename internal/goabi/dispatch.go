package goabi

import (
	"errors"
	"fmt"
	"reflect"
	"slices"
	"strconv"
	"strings"
)

// initTemplate renders the plugin instance and [InitFunc]. yaegi's run-time interface assertions are
// unreliable, so Create is assigned to a variable of the exact expected type: yaegi rejects a Create with any
// other signature when it compiles the dispatcher. A nil instance is reported as a problem (a load failure),
// apart from Create's own error.
const initTemplate = `var inst %[1]s

var create func() (%[1]s, error) = plugin.%[2]s

func %[3]s() (string, error) {
	v, err := create()
	if err != nil {
		return "", err
	}

	if v == nil {
		return %[4]s, nil
	}

	inst = v

	return "", nil
}
`

// ErrRender reports an interface the dispatcher cannot be rendered for.
var ErrRender = errors.New("goabi: cannot render dispatcher")

// RenderDispatcher returns the Go source of the dispatcher package for the named interface iface: it holds the
// plugin instance returned by the plugin package's Create and forwards one [CallPrefix]+<Method> function to
// each method. Every package a signature refers to is imported under a generated alias, so the output does
// not depend on package names. The output is deterministic.
func RenderDispatcher(iface reflect.Type) ([]byte, error) {
	if iface.Kind() != reflect.Interface || iface.Name() == "" || iface.PkgPath() == "" {
		return nil, fmt.Errorf("%w: %s is not a named interface type", ErrRender, iface)
	}

	rnd := renderer{aliases: map[string]string{iface.PkgPath(): ""}}

	for m := range iface.Methods() {
		if !m.IsExported() {
			return nil, fmt.Errorf("%w: method %s is unexported", ErrRender, m.Name)
		}

		err := rnd.collectFunc(m.Type)
		if err != nil {
			return nil, fmt.Errorf("method %s: %w", m.Name, err)
		}
	}

	rnd.assignAliases()

	return rnd.render(iface), nil
}

type renderer struct {
	aliases map[string]string // import path -> alias; filled with "" by collect, assigned by assignAliases
	b       strings.Builder
}

func (r *renderer) collectFunc(fn reflect.Type) error {
	for typ := range fn.Ins() {
		err := r.collect(typ)
		if err != nil {
			return err
		}
	}

	for typ := range fn.Outs() {
		err := r.collect(typ)
		if err != nil {
			return err
		}
	}

	return nil
}

// collect records the import paths typ refers to and rejects what cannot be written as a type expression.
func (r *renderer) collect(typ reflect.Type) error {
	if typ.Kind() == reflect.UnsafePointer {
		return fmt.Errorf("%w: unsafe.Pointer", ErrRender)
	}

	if typ.Name() != "" {
		return r.collectNamed(typ)
	}

	switch typ.Kind() { //nolint:exhaustive // every other kind is named (handled above) or rejected by default
	case reflect.Pointer, reflect.Slice, reflect.Array:
		return r.collect(typ.Elem())
	case reflect.Map:
		err := r.collect(typ.Key())
		if err != nil {
			return err
		}

		return r.collect(typ.Elem())
	case reflect.Struct:
		return r.collectFields(typ)
	default:
		return fmt.Errorf("%w: unnamed %s type %s", ErrRender, typ.Kind(), typ)
	}
}

// collectNamed records a named type's package: named types are referred to by name, their definition stays
// in their package.
func (r *renderer) collectNamed(typ reflect.Type) error {
	if strings.ContainsRune(typ.Name(), '[') {
		return fmt.Errorf("%w: generic type %s", ErrRender, typ)
	}

	if typ.PkgPath() != "" {
		r.aliases[typ.PkgPath()] = ""
	}

	return nil
}

func (r *renderer) collectFields(typ reflect.Type) error {
	for field := range typ.Fields() {
		if !field.IsExported() {
			return fmt.Errorf("%w: unexported field %s in %s", ErrRender, field.Name, typ)
		}

		err := r.collect(field.Type)
		if err != nil {
			return err
		}
	}

	return nil
}

func (r *renderer) sortedPaths() []string {
	paths := make([]string, 0, len(r.aliases))
	for p := range r.aliases {
		paths = append(paths, p)
	}

	slices.Sort(paths)

	return paths
}

func (r *renderer) assignAliases() {
	for i, p := range r.sortedPaths() {
		r.aliases[p] = "p" + strconv.Itoa(i)
	}
}

func (r *renderer) render(iface reflect.Type) []byte {
	r.printf("// Code generated by plg for %s. DO NOT EDIT.\n\npackage dispatch\n\nimport (\n", iface)

	for _, p := range r.sortedPaths() {
		r.printf("\t%s %s\n", r.aliases[p], strconv.Quote(p))
	}

	r.printf("\tplugin %s\n)\n\n", strconv.Quote(PluginImportPath))
	r.printf(initTemplate, r.typeExpr(iface), CreateFunc, InitFunc,
		strconv.Quote(CreateFunc+" returned a nil "+iface.String()))

	for m := range iface.Methods() {
		r.renderMethod(&m)
	}

	return []byte(r.b.String())
}

func (r *renderer) renderMethod(method *reflect.Method) {
	fn := method.Type
	params := make([]string, 0, fn.NumIn())
	args := make([]string, 0, fn.NumIn())

	for typ := range fn.Ins() {
		arg := "a" + strconv.Itoa(len(args))
		param := arg + " " + r.typeExpr(typ)

		if fn.IsVariadic() && len(args) == fn.NumIn()-1 {
			param = arg + " ..." + r.typeExpr(typ.Elem())
			arg += "..."
		}

		params = append(params, param)
		args = append(args, arg)
	}

	results := make([]string, 0, fn.NumOut())
	for typ := range fn.Outs() {
		results = append(results, r.typeExpr(typ))
	}

	call := "inst." + method.Name + "(" + strings.Join(args, ", ") + ")"
	if len(results) > 0 {
		call = "return " + call
	}

	r.printf("\nfunc %s%s(%s) (%s) {\n\t%s\n}\n",
		CallPrefix, method.Name, strings.Join(params, ", "), strings.Join(results, ", "), call)
}

// typeExpr writes typ as a type expression; collect has validated it.
func (r *renderer) typeExpr(typ reflect.Type) string {
	if typ.Name() != "" {
		if typ.PkgPath() == "" {
			return typ.Name() // predeclared
		}

		return r.aliases[typ.PkgPath()] + "." + typ.Name()
	}

	switch typ.Kind() { //nolint:exhaustive // collect admits only these unnamed kinds
	case reflect.Pointer:
		return "*" + r.typeExpr(typ.Elem())
	case reflect.Slice:
		return "[]" + r.typeExpr(typ.Elem())
	case reflect.Array:
		return "[" + strconv.Itoa(typ.Len()) + "]" + r.typeExpr(typ.Elem())
	case reflect.Map:
		return "map[" + r.typeExpr(typ.Key()) + "]" + r.typeExpr(typ.Elem())
	default: // reflect.Struct
		return r.structExpr(typ)
	}
}

func (r *renderer) structExpr(typ reflect.Type) string {
	fields := make([]string, 0, typ.NumField())

	for field := range typ.Fields() {
		expr := field.Name + " " + r.typeExpr(field.Type)
		if field.Anonymous {
			expr = r.typeExpr(field.Type)
		}

		if field.Tag != "" {
			expr += " " + strconv.Quote(string(field.Tag))
		}

		fields = append(fields, expr)
	}

	return "struct{ " + strings.Join(fields, "; ") + " }"
}

func (r *renderer) printf(format string, args ...any) {
	fmt.Fprintf(&r.b, format, args...)
}
