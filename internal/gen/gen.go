// Package gen implements `plg gen`: for interfaces declared in a contract package it generates the file that
// makes them usable with plg. Per interface, an adapter whose W<Method> fields plg fills with calls into a
// plugin, its forwarding methods and a compile-time assertion that it implements the interface (so a changed
// interface fails the build until the file is regenerated); for the file, an embed of the package's Go source,
// which the Go guest interprets, and an init that registers the contracts.
//
// A contract package may import only the Go guest's allowlist: the guest receives its source, and nothing else.
package gen

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/build"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/heynemann/go-plg/internal/contractsrc"
	"github.com/heynemann/go-plg/internal/goallow"
)

// Errors returned by [Generate] and [Write], wrapped with details.
var (
	// ErrInterfaceName reports an interface name argument that is missing, not an identifier or repeated.
	ErrInterfaceName = errors.New("invalid interface names")
	// ErrPackage reports a directory without a contract package plg gen can read and type-check.
	ErrPackage = errors.New("cannot load the contract package")
	// ErrImport reports a contract package importing a package the Go guest does not allow.
	ErrImport = errors.New("the contract package imports packages the Go guest does not allow")
	// ErrInterface reports a name that is not a non-generic interface plg can adapt.
	ErrInterface = errors.New("not an interface plg can adapt")
	// ErrNotGenerated reports an output file that plg gen did not generate, which it never overwrites.
	ErrNotGenerated = errors.New("refusing to overwrite a file plg gen did not generate")
)

const (
	// plgImportPath is the import path of the plg package the generated code registers with.
	plgImportPath = "github.com/heynemann/go-plg"
	// generatedMode is the generated file's permissions: those of any source file.
	generatedMode = 0o644
)

// File is a generated Go file.
type File struct {
	// Name is the file's base name, in the package directory.
	Name string
	// Source is the file's gofmt-formatted content.
	Source []byte
}

// Generate generates the plg file for the named interfaces of the Go package in dir: `<first name in lower
// case>_plg.go`. The output depends only on the package's source and the names, in order.
func Generate(dir string, interfaces []string) (File, error) {
	err := checkNames(interfaces)
	if err != nil {
		return File{}, err
	}

	pkg, err := load(dir)
	if err != nil {
		return File{}, err
	}

	ifaces := make([]*types.Interface, len(interfaces))
	for i, name := range interfaces {
		ifaces[i], err = lookupInterface(pkg, name)
		if err != nil {
			return File{}, err
		}
	}

	src, err := render(pkg, interfaces, ifaces)
	if err != nil {
		return File{}, err
	}

	return File{Name: strings.ToLower(interfaces[0]) + "_plg.go", Source: src}, nil
}

// Write writes file into dir, unless the file there was not generated by plg gen. An identical file is left
// untouched.
func Write(dir string, file File) error {
	target := filepath.Join(dir, file.Name)

	old, err := fs.ReadFile(os.DirFS(dir), file.Name)
	switch {
	case errors.Is(err, fs.ErrNotExist): // a new file
	case err != nil:
		return fmt.Errorf("reading %s: %w", target, err)
	case !contractsrc.IsGenerated(old):
		return fmt.Errorf("%w: %s", ErrNotGenerated, target)
	case bytes.Equal(old, file.Source):
		return nil
	default: // plg gen's previous output, replaced below
	}

	err = os.WriteFile(target, file.Source, generatedMode)
	if err != nil {
		return fmt.Errorf("writing %s: %w", target, err)
	}

	return nil
}

func checkNames(names []string) error {
	if len(names) == 0 {
		return fmt.Errorf("%w: none given", ErrInterfaceName)
	}

	seen := make(map[string]bool, len(names))
	for _, name := range names {
		if !token.IsIdentifier(name) {
			return fmt.Errorf("%w: %q is not a Go identifier", ErrInterfaceName, name)
		}

		if seen[name] {
			return fmt.Errorf("%w: %s is listed twice", ErrInterfaceName, name)
		}

		seen[name] = true
	}

	return nil
}

// load parses the package's files the guest receives (see [contractsrc.Include]), checks their imports
// against the guest allowlist and type-checks those that build on this platform.
func load(dir string) (*types.Package, error) {
	pkgDir := os.DirFS(dir)

	entries, err := fs.ReadDir(pkgDir, ".")
	if err != nil {
		return nil, fmt.Errorf("%w: %w", ErrPackage, err)
	}

	fset := token.NewFileSet()

	var (
		files      []*ast.File
		disallowed []string
	)

	for _, entry := range entries {
		file, builds, parseErr := parseFile(fset, dir, pkgDir, entry)
		if parseErr != nil {
			return nil, parseErr
		}

		if file == nil {
			continue
		}

		disallowed = append(disallowed, disallowedImports(fset, file)...)

		if builds {
			files = append(files, file)
		}
	}

	if len(disallowed) > 0 {
		return nil, fmt.Errorf("%w (the guest interprets its source and links only its allowlist):\n%s\n"+
			"allowed: %s", ErrImport, strings.Join(disallowed, "\n"), strings.Join(goallow.Packages(), " "))
	}

	if len(files) == 0 {
		return nil, fmt.Errorf("%w: no Go source files in %s", ErrPackage, dir)
	}

	// The allowlist was checked above, so only standard library packages are imported: their export data,
	// which the go command keeps in its build cache, is much faster to load than their source.
	config := types.Config{Importer: importer.ForCompiler(fset, "gc", nil)}

	pkg, err := config.Check(files[0].Name.Name, fset, files, nil)
	if err != nil {
		return nil, fmt.Errorf("%w: %w", ErrPackage, err)
	}

	return pkg, nil
}

// parseFile parses a directory entry the guest receives, and reports whether it builds on this platform. It
// returns a nil file for the other entries.
func parseFile(fset *token.FileSet, dir string, pkgDir fs.FS, entry fs.DirEntry) (*ast.File, bool, error) {
	name := entry.Name()
	if !entry.Type().IsRegular() || filepath.Ext(name) != ".go" {
		return nil, false, nil
	}

	src, err := fs.ReadFile(pkgDir, name)
	if err != nil {
		return nil, false, fmt.Errorf("%w: %w", ErrPackage, err)
	}

	if !contractsrc.Include(name, src) {
		return nil, false, nil
	}

	file, err := parser.ParseFile(fset, name, src, parser.SkipObjectResolution)
	if err != nil {
		return nil, false, fmt.Errorf("%w: %w", ErrPackage, err)
	}

	platform := build.Default
	platform.OpenFile = func(string) (io.ReadCloser, error) { return io.NopCloser(bytes.NewReader(src)), nil }

	match, err := platform.MatchFile(dir, name)
	if err != nil {
		return nil, false, fmt.Errorf("%w: %w", ErrPackage, err)
	}

	return file, match, nil
}

// disallowedImports lists the imports of file outside the guest allowlist, with their positions.
func disallowedImports(fset *token.FileSet, file *ast.File) []string {
	var disallowed []string

	for _, imp := range file.Imports {
		// Import paths cannot contain quotes; one spelled with escapes (legal, unheard of) is refused as written.
		if !goallow.Allowed(strings.Trim(imp.Path.Value, "\"`")) {
			disallowed = append(disallowed, fmt.Sprintf("\t%s: %s", fset.Position(imp.Path.Pos()), imp.Path.Value))
		}
	}

	return disallowed
}

// lookupInterface returns the interface the package declares as name.
func lookupInterface(pkg *types.Package, name string) (*types.Interface, error) {
	obj, ok := pkg.Scope().Lookup(name).(*types.TypeName)
	if !ok {
		return nil, fmt.Errorf("%w: package %s declares no type %s", ErrInterface, pkg.Name(), name)
	}

	if generic, isGeneric := obj.Type().(interface{ TypeParams() *types.TypeParamList }); isGeneric &&
		generic.TypeParams().Len() > 0 {
		return nil, fmt.Errorf("%w: %s is generic", ErrInterface, name)
	}

	iface, ok := obj.Type().Underlying().(*types.Interface)
	if !ok {
		return nil, fmt.Errorf("%w: %s is a %s", ErrInterface, name, obj.Type().Underlying())
	}

	if !iface.IsMethodSet() {
		return nil, fmt.Errorf("%w: %s is a type constraint", ErrInterface, name)
	}

	for m := range iface.Methods() {
		if hasMethod(iface, "W"+m.Name()) {
			return nil, fmt.Errorf("%w: %s has methods %s and W%[3]s; the adapter's field W%[3]s for %[3]s "+
				"would clash with method W%[3]s", ErrInterface, name, m.Name())
		}
	}

	return iface, nil
}

func hasMethod(iface *types.Interface, name string) bool {
	for m := range iface.Methods() {
		if m.Name() == name {
			return true
		}
	}

	return false
}
