// Package gen implements `plg gen`: for interfaces declared in a contract package it generates the file that
// makes them usable with plg. Per interface, an adapter whose W<Method> fields plg fills with calls into a
// plugin, its forwarding methods and a compile-time assertion that it implements the interface (so a changed
// interface fails the build until the file is regenerated); for the file, an embed of the package's Go source,
// which the Go guest interprets, and an init that registers the contracts.
//
// Unless [Options.Generic], each interface also gets fast paths (see plg.Contract.Fast): an adapter calling
// plugins through plgimpl.Invoker with a call type per method, and an encoder and a decoder per composite type
// its methods reach, which encode exactly as plg's reflective codec, with the fingerprint of that layout. An
// interface whose methods break the interface contract or use types the encoding does not support gets none
// (registering it fails at init anyway, with the precise reason).
//
// A contract package may import only the Go guest's allowlist: the guest receives its source, and nothing else.
package gen

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/build"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/heynemann/go-plg/internal/buildguest"
	"github.com/heynemann/go-plg/internal/contractsrc"
	"github.com/heynemann/go-plg/internal/directive"
	"github.com/heynemann/go-plg/internal/goallow"
	"github.com/heynemann/go-plg/internal/gorestrict"
)

// Errors returned by [Generate] and [Write], wrapped with details.
var (
	// ErrInterfaceName reports an interface name argument that is missing, not an identifier or repeated.
	ErrInterfaceName = errors.New("invalid interface names")
	// ErrPackage reports a directory without a contract package plg gen can read and type-check.
	ErrPackage = errors.New("cannot load the contract package")
	// ErrImport reports a contract package importing a package the Go guest does not allow.
	ErrImport = errors.New("the contract package imports packages the Go guest does not allow")
	// ErrInterface reports a name that is not a non-generic interface plg can adapt.
	ErrInterface = errors.New("not an interface plg can adapt")
	// ErrNotGenerated reports an output file that plg gen did not generate, which it never overwrites.
	ErrNotGenerated = errors.New("refusing to overwrite a file plg gen did not generate")
	// ErrPredeclared reports a contract package redeclaring a predeclared identifier the generated code needs
	// and cannot name otherwise.
	ErrPredeclared = errors.New("the contract package redeclares a predeclared identifier plg gen's code needs")
)

const (
	// plgImportPath is the import path of the plg package the generated code registers with.
	plgImportPath = "github.com/heynemann/go-plg"
	// generatedMode is the generated file's permissions: those of any source file.
	generatedMode = 0o644
)

// File is a generated Go file.
type File struct {
	// Name is the file's base name, in the package directory.
	Name string
	// Source is the file's gofmt-formatted content.
	Source []byte
}

// Options configure [Generate].
type Options struct {
	// Generic leaves the fast paths out: plg then serves the interfaces with its generic binder.
	Generic bool
}

// Generate generates the plg file for the named interfaces of the Go package in dir: `<first name in lower
// case>_plg.go`. The output depends only on the package's source, the names, in order, and opts.
func Generate(dir string, interfaces []string, opts Options) (File, error) {
	err := checkNames(interfaces)
	if err != nil {
		return File{}, err
	}

	pkg, err := Load(dir, "", nil)
	if err != nil {
		return File{}, err
	}

	ifaces := make([]*types.Interface, len(interfaces))
	for i, name := range interfaces {
		_, ifaces[i], err = Interface(pkg.Types, name)
		if err != nil {
			return File{}, err
		}

		_, err = pkg.Directives(name)
		if err != nil {
			return File{}, err
		}
	}

	src, err := render(pkg.Types, interfaces, ifaces, opts)
	if err != nil {
		return File{}, err
	}

	return File{Name: strings.ToLower(interfaces[0]) + "_plg.go", Source: src}, nil
}

// Write writes file into dir, unless the file there was not generated by plg gen. An identical file is left
// untouched.
func Write(dir string, file File) error {
	target := filepath.Join(dir, file.Name)

	old, err := fs.ReadFile(os.DirFS(dir), file.Name)
	switch {
	case errors.Is(err, fs.ErrNotExist): // a new file
	case err != nil:
		return fmt.Errorf("reading %s: %w", target, err)
	case !contractsrc.IsGenerated(old):
		return fmt.Errorf("%w: %s", ErrNotGenerated, target)
	case bytes.Equal(old, file.Source):
		return nil
	default: // plg gen's previous output, replaced below
	}

	err = os.WriteFile(target, file.Source, generatedMode)
	if err != nil {
		return fmt.Errorf("writing %s: %w", target, err)
	}

	return nil
}

func checkNames(names []string) error {
	if len(names) == 0 {
		return fmt.Errorf("%w: none given", ErrInterfaceName)
	}

	seen := make(map[string]bool, len(names))
	for _, name := range names {
		if !token.IsIdentifier(name) {
			return fmt.Errorf("%w: %q is not a Go identifier", ErrInterfaceName, name)
		}

		if seen[name] {
			return fmt.Errorf("%w: %s is listed twice", ErrInterfaceName, name)
		}

		seen[name] = true
	}

	return nil
}

// Package is a contract package, type-checked.
type Package struct {
	// Types is the package's type information.
	Types *types.Package
	fset  *token.FileSet
	files []*ast.File // the files type-checked
}

// Load parses the files of the Go package in dir that the guest receives (see [contractsrc.Include]), checks
// their imports against the guest allowlist and type-checks those that build on this platform: the contract
// package as plg gen and plg validate see it. The package's path is importPath; empty means its name. The
// standard library comes from imp (nil means a gc importer of its own), so packages type-checked with the same
// importer share its packages.
func Load(dir, importPath string, imp types.Importer) (*Package, error) {
	pkgDir := os.DirFS(dir)

	entries, err := fs.ReadDir(pkgDir, ".")
	if err != nil {
		return nil, fmt.Errorf("%w: %w", ErrPackage, err)
	}

	fset := token.NewFileSet()

	var (
		files      []*ast.File
		disallowed []string
	)

	for _, entry := range entries {
		file, builds, parseErr := parseFile(fset, dir, pkgDir, entry)
		if parseErr != nil {
			return nil, parseErr
		}

		if file == nil {
			continue
		}

		for _, refused := range gorestrict.Refused(fset, file, goallow.Allowed) {
			disallowed = append(disallowed, "\t"+refused)
		}

		if builds {
			files = append(files, file)
		}
	}

	if len(disallowed) > 0 {
		return nil, fmt.Errorf("%w (the guest interprets its source and links only its allowlist):\n%s\n"+
			"allowed: %s", ErrImport, strings.Join(disallowed, "\n"), strings.Join(goallow.Packages(), " "))
	}

	if len(files) == 0 {
		return nil, fmt.Errorf("%w: no Go source files in %s", ErrPackage, dir)
	}

	pkg, err := check(fset, files, importPath, imp)
	if err != nil {
		return nil, err
	}

	return &Package{Types: pkg, fset: fset, files: files}, nil
}

// Directives returns the plg directives on the doc comment of the type the package declares as name (see package
// directive), its guest packages checked as plg build-guest checks them: a malformed one fails with
// [directive.ErrDirective], naming where it is, as does a //plg:validation naming no type of the package. A type
// without them has none.
func (p *Package) Directives(name string) (directive.Directives, error) {
	spec, doc := p.typeSpec(name)
	if spec == nil {
		return directive.Directives{}, nil
	}

	dirs, err := directive.Parse(doc, buildguest.CheckPackages)
	if err == nil && dirs.Validation != "" {
		if _, isType := p.Types.Scope().Lookup(dirs.Validation).(*types.TypeName); !isType {
			err = fmt.Errorf("%w: //plg:validation %s: package %s declares no type %[2]s", directive.ErrDirective,
				dirs.Validation, p.Types.Name())
		}
	}

	if err != nil {
		return directive.Directives{}, fmt.Errorf("%s: %s: %w", p.fset.Position(spec.Pos()), name, err)
	}

	return dirs, nil
}

// typeSpec returns the spec declaring the type name in the package's files, and its doc comment; nil when there
// is none.
func (p *Package) typeSpec(name string) (*ast.TypeSpec, *ast.CommentGroup) {
	for _, file := range p.files {
		for _, decl := range file.Decls {
			if spec, doc := typeSpec(decl, name); spec != nil {
				return spec, doc
			}
		}
	}

	return nil, nil
}

// typeSpec returns the spec declaring the type name in decl, and its doc comment: the spec's own in a group, the
// declaration's otherwise; nil when decl does not declare it.
func typeSpec(decl ast.Decl, name string) (*ast.TypeSpec, *ast.CommentGroup) {
	gen, ok := decl.(*ast.GenDecl)
	if !ok || gen.Tok != token.TYPE {
		return nil, nil
	}

	for _, spec := range gen.Specs {
		typeSpec, isType := spec.(*ast.TypeSpec)
		if !isType || typeSpec.Name.Name != name {
			continue
		}

		if typeSpec.Doc == nil && len(gen.Specs) == 1 {
			return typeSpec, gen.Doc
		}

		return typeSpec, typeSpec.Doc
	}

	return nil, nil
}

// check type-checks the files of a package as Load describes.
func check(fset *token.FileSet, files []*ast.File, importPath string, imp types.Importer) (*types.Package, error) {
	// The allowlist was checked, so only standard library packages are imported: their export data, which the go
	// command keeps in its build cache, is much faster to load than their source.
	if imp == nil {
		imp = importer.ForCompiler(fset, "gc", nil)
	}

	if importPath == "" {
		importPath = files[0].Name.Name
	}

	config := types.Config{Importer: imp}

	pkg, err := config.Check(importPath, fset, files, nil)
	if err != nil {
		return nil, fmt.Errorf("%w: %w", ErrPackage, err)
	}

	return pkg, nil
}

// parseFile parses a directory entry the guest receives, and reports whether it builds on this platform. It
// returns a nil file for the other entries.
func parseFile(fset *token.FileSet, dir string, pkgDir fs.FS, entry fs.DirEntry) (*ast.File, bool, error) {
	name := entry.Name()
	if !entry.Type().IsRegular() || filepath.Ext(name) != ".go" {
		return nil, false, nil
	}

	src, err := fs.ReadFile(pkgDir, name)
	if err != nil {
		return nil, false, fmt.Errorf("%w: %w", ErrPackage, err)
	}

	if !contractsrc.Include(name, src) {
		return nil, false, nil
	}

	file, err := parser.ParseFile(fset, name, src, parser.SkipObjectResolution|parser.ParseComments)
	if err != nil {
		return nil, false, fmt.Errorf("%w: %w", ErrPackage, err)
	}

	platform := build.Default
	platform.OpenFile = func(string) (io.ReadCloser, error) { return io.NopCloser(bytes.NewReader(src)), nil }

	match, err := platform.MatchFile(dir, name)
	if err != nil {
		return nil, false, fmt.Errorf("%w: %w", ErrPackage, err)
	}

	return file, match, nil
}

// Interface returns the interface the package declares as name, and its underlying interface: a named,
// non-generic interface that is not a type constraint, none of whose methods M has a sibling WM (the adapter's
// field for M).
func Interface(pkg *types.Package, name string) (*types.Named, *types.Interface, error) {
	obj, ok := pkg.Scope().Lookup(name).(*types.TypeName)
	if !ok {
		return nil, nil, fmt.Errorf("%w: package %s declares no type %s", ErrInterface, pkg.Name(), name)
	}

	if generic, isGeneric := obj.Type().(interface{ TypeParams() *types.TypeParamList }); isGeneric &&
		generic.TypeParams().Len() > 0 {
		return nil, nil, fmt.Errorf("%w: %s is generic", ErrInterface, name)
	}

	iface, ok := obj.Type().Underlying().(*types.Interface)
	if !ok {
		return nil, nil, fmt.Errorf("%w: %s is a %s", ErrInterface, name, obj.Type().Underlying())
	}

	if !iface.IsMethodSet() {
		return nil, nil, fmt.Errorf("%w: %s is a type constraint", ErrInterface, name)
	}

	for m := range iface.Methods() {
		if hasMethod(iface, "W"+m.Name()) {
			return nil, nil, fmt.Errorf("%w: %s has methods %s and W%[3]s; the adapter's field W%[3]s for %[3]s "+
				"would clash with method W%[3]s", ErrInterface, name, m.Name())
		}
	}

	named, ok := types.Unalias(obj.Type()).(*types.Named)
	if !ok {
		return nil, nil, fmt.Errorf("%w: %s is an alias of an unnamed interface", ErrInterface, name)
	}

	return named, iface, nil
}

func hasMethod(iface *types.Interface, name string) bool {
	for m := range iface.Methods() {
		if m.Name() == name {
			return true
		}
	}

	return false
}
