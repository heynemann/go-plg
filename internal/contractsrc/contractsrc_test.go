const generated = contractsrc.Header + "\n\npackage c\n"

func TestIsGenerated(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		src  string
		want bool
	}{
		{name: "plg gen output", src: generated, want: true},
		{name: "CRLF line endings", src: contractsrc.Header + "\r\n\r\npackage c\r\n", want: true},
		{name: "header only", src: contractsrc.Header, want: true},
		{name: "empty", src: "", want: false},
		{name: "hand-written", src: "package c\n", want: false},
		{name: "another generator", src: "// Code generated by stringer. DO NOT EDIT.\n\npackage c\n", want: false},
		{name: "header not first", src: "// Copyright.\n" + generated, want: false},
		{name: "header with trailing text", src: contractsrc.Header + " Really.\npackage c\n", want: false},
		{name: "indented header", src: " " + generated, want: false},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			assert.Equal(t, tc.want, contractsrc.IsGenerated([]byte(tc.src)))
		})
	}
}

func TestInclude(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name, file, src string
		want            bool
	}{
		{name: "contract source", file: "contract.go", src: "package c\n", want: true},
		{name: "nested source", file: "sub/contract.go", src: "package sub\n", want: true},
		{name: "test file", file: "contract_test.go", src: "package c\n", want: false},
		{name: "nested test file", file: "sub/contract_test.go", src: "package sub\n", want: false},
		{name: "plg gen output", file: "fooer_plg.go", src: generated, want: false},
		{name: "hand-written file named like plg gen output", file: "fooer_plg.go", src: "package c\n", want: true},
		{name: "file named like a test, not Go", file: "notes_test.go.txt", src: "x", want: true},
		{name: "non-Go file with the header", file: "README", src: generated, want: true},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			assert.Equal(t, tc.want, contractsrc.Include(tc.file, []byte(tc.src)))
		})
	}
}

func TestSnapshot(t *testing.T) {
	t.Parallel()

	src := fstest.MapFS{
		"contract.go":      {Data: []byte("package c\n")},
		"types.go":         {Data: []byte("package c\n\ntype T int\n")},
		"contract_test.go": {Data: []byte("package c\n")},
		"fooer_plg.go":     {Data: []byte(generated)},
		"doc/README":       {Data: []byte("docs")},
		"link.go":          {Data: []byte("x"), Mode: fs.ModeSymlink},
	}

	snapshot, err := contractsrc.Snapshot(src)
	require.NoError(t, err)

	var names []string

	require.NoError(t, fs.WalkDir(snapshot, ".", func(name string, d fs.DirEntry, err error) error {
		if err == nil && !d.IsDir() {
			names = append(names, name)
		}

		return err
	}))
	assert.Equal(t, []string{"contract.go", "doc/README", "types.go"}, names)

	data, err := fs.ReadFile(snapshot, "types.go")
	require.NoError(t, err)
	assert.Equal(t, "package c\n\ntype T int\n", string(data))

	src["types.go"].Data[0] = 'P'
	data, err = fs.ReadFile(snapshot, "types.go")
	require.NoError(t, err)
	assert.Equal(t, "package c\n\ntype T int\n", string(data), "the snapshot does not share the source's buffers")
}

func TestSnapshotErrors(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		src  fs.FS
		want error
		msg  string
	}{
		{name: "empty", src: fstest.MapFS{}, want: contractsrc.ErrNoGoFiles},
		{
			name: "Go files only below the root", want: contractsrc.ErrNoGoFiles,
			src: fstest.MapFS{"sub/x.go": {Data: []byte("package x\n")}, "README": {}},
		},
		{
			name: "only tests and generated files", want: contractsrc.ErrNoGoFiles,
			src: fstest.MapFS{"c_test.go": {Data: []byte("package c\n")}, "c_plg.go": {Data: []byte(generated)}},
		},
		{name: "unreadable directory", src: brokenFS{}, want: errBroken, msg: "reading the source"},
		{name: "unreadable file", src: unreadableFile{}, want: errBroken, msg: "reading the source"},
		{name: "inconsistent tree", src: fileAndDir{}, msg: "reading the source: memfs: conflicting path"},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			snapshot, err := contractsrc.Snapshot(tc.src)
			require.Error(t, err)
			assert.Nil(t, snapshot)

			if tc.want != nil {
				require.ErrorIs(t, err, tc.want)
			}

			assert.ErrorContains(t, err, tc.msg)
		})
	}
}

var errBroken = errors.New("broken")

// brokenFS fails to open anything.
type brokenFS struct{}

func (brokenFS) Open(string) (fs.File, error) { return nil, errBroken }

// unreadableFile lists one Go file that fails to open.
type unreadableFile struct{}

func (unreadableFile) Open(name string) (fs.File, error) {
	if name == "." {
		return fstest.MapFS{"c.go": {}}.Open(".") //nolint:wrapcheck // test double
	}

	return nil, errBroken
}

// fileAndDir lists "a" twice, as a file and as a directory holding a Go file: a tree no real file system has,
// which the snapshot must refuse rather than build.
type fileAndDir struct{}

func (f fileAndDir) Open(name string) (fs.File, error) {
	entries, err := f.ReadDir(name)

	return &dir{entries: entries}, err
}

func (fileAndDir) ReadDir(name string) ([]fs.DirEntry, error) {
	if name == "." {
		return []fs.DirEntry{entry{name: "a"}, entry{name: "a", dir: true}}, nil
	}

	return []fs.DirEntry{entry{name: "c.go"}}, nil
}

func (fileAndDir) ReadFile(string) ([]byte, error) { return []byte("package c\n"), nil }

type dir struct{ entries []fs.DirEntry }

func (*dir) Stat() (fs.FileInfo, error) { return entry{dir: true}, nil }
func (*dir) Read([]byte) (int, error)   { return 0, errBroken }
func (*dir) Close() error               { return nil }

type entry struct {
	name string
	dir  bool
}

func (e entry) Name() string               { return e.name }
func (e entry) IsDir() bool                { return e.dir }
func (e entry) Type() fs.FileMode          { return e.Mode().Type() }
func (e entry) Info() (fs.FileInfo, error) { return e, nil }
func (entry) Size() int64                  { return 0 }
func (entry) ModTime() time.Time           { return time.Time{} }
func (entry) Sys() any                     { return nil }

func (e entry) Mode() fs.FileMode {
	if e.dir {
		return fs.ModeDir
	}

	return 0
}
