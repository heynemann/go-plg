// Package contractsrc decides which files of a contract package the Go guest interprets. `plg gen` embeds every
// .go file of the package (go:embed has no exclusions); test files and the files plg gen generated (which import
// plg itself) are dropped here, when the contract is registered, and plg gen checks the imports of exactly the
// files kept.
package contractsrc

import (
	"bytes"
	"errors"
	"fmt"
	"io/fs"
	"path"
	"strings"

	"github.com/heynemann/go-plg/internal/memfs"
)

// Header is the first line of every file plg gen generates; it follows Go's convention for generated code.
const Header = "// Code generated by plg gen. DO NOT EDIT."

// ErrNoGoFiles reports a contract source without a Go file at its root after filtering.
var ErrNoGoFiles = errors.New("source has no .go file at its root")

// IsGenerated reports whether src is a file plg gen generated.
func IsGenerated(src []byte) bool {
	line, _, _ := bytes.Cut(src, []byte("\n"))

	return string(bytes.TrimSuffix(line, []byte("\r"))) == Header
}

// Include reports whether the contract file name with contents src goes to the guest: every file except Go
// test files and the files plg gen generated.
func Include(name string, src []byte) bool {
	if path.Ext(name) != ".go" {
		return true
	}

	return !strings.HasSuffix(name, "_test.go") && !IsGenerated(src)
}

// Snapshot copies the files of src that [Include] keeps, so every plugin of the contract sees the same files.
// It fails if src cannot be read or if no Go file is left at its root.
func Snapshot(src fs.FS) (*memfs.FS, error) {
	var tree memfs.Builder

	err := fs.WalkDir(src, ".", func(name string, d fs.DirEntry, err error) error {
		if err != nil || !d.Type().IsRegular() {
			return err
		}

		data, err := fs.ReadFile(src, name)
		if err != nil {
			return err //nolint:wrapcheck // wrapped once below, with the walk's other errors
		}

		if !Include(name, data) {
			return nil
		}

		return tree.Add(name, data)
	})
	if err != nil {
		return nil, fmt.Errorf("reading the source: %w", err)
	}

	snapshot, err := tree.Build()
	if err != nil {
		return nil, fmt.Errorf("reading the source: %w", err)
	}

	goFiles, err := fs.Glob(snapshot, "*.go")
	if err != nil || len(goFiles) == 0 {
		return nil, ErrNoGoFiles
	}

	return snapshot, nil
}
